async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Connected to MongoDB Atlas');

    await Actor.deleteMany({});
    console.log('🗑️  Cleared existing actors');

    for (const actorData of ACTORS) {
      const actor = new Actor(actorData);
      await actor.save();
      console.log(`✅ Seeded: ${actorData.name}`);
    }

    console.log(`\n🌍 Seeded ${ACTORS.length} countries with relations & events`);
    console.log('📌 Remember to create the Atlas Search index using atlasSearch.json');
  } catch (err) {
    console.error('❌ Seed error:', err);
  } finally {
    await mongoose.disconnect();
    process.exit(0);
  }
}

seed();
